const I18n = (() => {
  let lang = localStorage.getItem('zf_lang') || 'uz';

  const t = (key, fallback) => {
    const val = TRANSLATIONS[lang]?.[key] || TRANSLATIONS.uz[key] || fallback || key;
    return val;
  };

  const setLang = (newLang) => {
    if (!TRANSLATIONS[newLang]) return;
    lang = newLang;
    localStorage.setItem('zf_lang', lang);
    applyTranslations();
    document.getElementById('lang-label').textContent = lang.toUpperCase();
  };

  const getLang = () => lang;

  const applyTranslations = () => {
    document.querySelectorAll('[data-i18n]').forEach(el => {
      el.textContent = t(el.dataset.i18n);
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
      el.placeholder = t(el.dataset.i18nPlaceholder);
    });
  };

  const formatPrice = (amount) => {
    const formatted = new Intl.NumberFormat('uz-UZ').format(amount);
    return `${formatted} ${t('currency')}`;
  };

  return { t, setLang, getLang, applyTranslations, formatPrice };
})();
